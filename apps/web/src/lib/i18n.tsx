export type Locale = "fa" | "en";
const dictionaries: Record<Locale, Record<MessageKey, string>> = { fa, en };

interface I18n {
  locale: Locale;
  dir: "rtl" | "ltr";
  t: (key: MessageKey) => string;
  /** Translate a dynamic status/enum value, falling back to the raw value. */
  ts: (prefix: "status" | "rights" | "role" | "mode", value: string) => string;
  setLocale: (l: Locale) => void;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("fa");
  // Guards the persist-effect below from firing (with the still-default "fa")
  // before this read-from-storage effect has had a chance to run first —
  // without it the two effects race on mount and the stored preference gets
  // clobbered back to "fa" on every reload.
  const [ready, setReady] = useState(false);
  useEffect(() => {
    const saved = localStorage.getItem("rf-locale");
    if (saved === "en" || saved === "fa") setLocale(saved);
    setReady(true);
  }, []);
  useEffect(() => {
    if (!ready) return;
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";
    localStorage.setItem("rf-locale", locale);
  }, [locale, ready]);
  const value = useMemo<I18n>(() => {
    const dict = dictionaries[locale];
    return {
      locale,
      dir: locale === "fa" ? "rtl" : "ltr",
      t: (k) => dict[k] ?? k,
      ts: (prefix, v) => (dict as Record<string, string>)[`${prefix}.${v}`] ?? v,
      setLocale,
    };
  }, [locale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
